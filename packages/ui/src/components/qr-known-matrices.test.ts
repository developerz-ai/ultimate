const draw = (modules: readonly (readonly boolean[])[]): string[] =>
  modules.map((row) => row.map((dark) => (dark ? '#' : '.')).join(''));

describe('encodeQr against reference matrices', () => {
  TEXTS.forEach((text, index) => {
    test(`version ${index + 1}: ${JSON.stringify(text)} matches the reference module for module`, () => {
      const matrix = encodeQr(text);
      expect(matrix.version).toBe(index + 1);
      expect(draw(matrix.modules)).toEqual([...(MATRICES[index] ?? [])]);
    });
  });
});
