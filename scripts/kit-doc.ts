#!/usr/bin/env bun
// Generate the agent-kit table in `wiki/Agents.md` from `kit/registry.ts` — name, kind, the path it
// lands on, what it is for — and refuse a committed page that has drifted from the registry.
//
// A hand-written table of the kit is a second list of what `x kit` writes, free to go stale the
// day a skill is added. The region between the markers is the registry's projection and nothing else.
//
//   bun run scripts/kit-doc.ts [--check | --write] [--json]

// why: host-separator paths to the page; Bun ships no path API.
import { join } from 'node:path';
import { KIT_ENTRIES } from '../packages/cli/src/kit/registry';
import { names } from '../packages/cli/src/templates/naming';
import { flagBool, parseScriptArgs } from './lib/args';
import type { Finding } from './lib/log';
import { report } from './lib/log';
import { repoRoot } from './lib/run';

const SCRIPT = 'kit-doc';
export const KIT_PAGE = 'wiki/Agents.md';
export const KIT_BEGIN =
  '<!-- kit-doc:begin — generated by `bun run scripts/kit-doc.ts --write` -->';
export const KIT_END = '<!-- kit-doc:end -->';
const FIX = 'bun run scripts/kit-doc.ts --write';

/** The front matter's `description:` — one line in every managed file, read as text. */
const descriptionOf = (contents: string): string =>
  /^description:\s*(.+)$/m.exec(contents)?.[1]?.trim() ?? '';

const cell = (text: string): string => text.replaceAll('|', '\\|');

/** The first sentence: a row is a pointer, the file holds the rest. */
const firstSentence = (text: string): string => {
  const end = text.search(/\.(\s|$)/);
  return end === -1 ? text : text.slice(0, end + 1);
};

/** The table, rendered against a placeholder app: the registry's rows do not depend on its name. */
export function renderKitTable(): string {
  const app = names('my-app');
  const rows = KIT_ENTRIES.map((entry) => {
    // The placeholder app's name reads as prose: the page describes every app.
    const description = firstSentence(descriptionOf(entry.render(app))).replaceAll(
      'my-app',
      'the app',
    );
    return `| \`${entry.name}\` | ${entry.kind} | \`${entry.path}\` | ${cell(description)} |`;
  });
  return ['| Name | Kind | Lands at | For |', '|---|---|---|---|', ...rows].join('\n');
}

/** The page with the marked region replaced; `undefined` when the markers are missing. */
export function spliceKitTable(page: string): string | undefined {
  const begin = page.indexOf(KIT_BEGIN);
  const end = page.indexOf(KIT_END);
  if (begin === -1 || end === -1 || end < begin) return undefined;
  return `${page.slice(0, begin)}${KIT_BEGIN}\n\n${renderKitTable()}\n\n${page.slice(end)}`;
}

export async function kitDocFindings(root: string): Promise<readonly Finding[]> {
  const file = Bun.file(join(root, KIT_PAGE));
  const page = (await file.exists()) ? await file.text() : undefined;
  const next = page === undefined ? undefined : spliceKitTable(page);
  if (next === undefined) {
    return [
      {
        code: 'X_KIT_DOC_UNSCANNED',
        cause: `${KIT_PAGE} is missing or carries no ${KIT_BEGIN} … ${KIT_END} markers, so the kit table has nowhere to land`,
        fix: `printf '%s\\n' '${KIT_BEGIN}' '${KIT_END}' >> ${KIT_PAGE} && bun run scripts/kit-doc.ts --write   # then move the two lines to where the table belongs`,
        at: KIT_PAGE,
      },
    ];
  }
  if (next === page) return [];
  return [
    {
      code: 'X_KIT_DOC_DRIFT',
      cause: `the kit table in ${KIT_PAGE} does not match kit/registry.ts (${KIT_ENTRIES.length} entries)`,
      fix: FIX,
      at: KIT_PAGE,
    },
  ];
}

if (import.meta.main) {
  const args = parseScriptArgs(Bun.argv.slice(2));
  const root = repoRoot();
  if (flagBool(args, 'write')) {
    const path = join(root, KIT_PAGE);
    const next = spliceKitTable(await Bun.file(path).text());
    if (next !== undefined) await Bun.write(path, next);
  }
  const findings = await kitDocFindings(root);
  report(
    {
      ok: findings.length === 0,
      script: SCRIPT,
      summary:
        findings.length === 0 ? `${KIT_PAGE} kit table matches the registry` : 'kit table drift',
      findings,
    },
    args.json,
  );
}
